-- 0.1.28: native visible copper spans for rail-validated C-mast graph.
-- 35 kV is the railway design label, NOT a real voltage simulation.
-- Owned helper poles are the only copper endpoints. No manual Lua line art.
local M={}
local geo=require("scripts.native_wire_geometry_028")
local HELPER="em-35kv-wire-anchor"
local LEGACY="em-25kv-wire-probe-anchor" -- migrations ONLY, never newly placed.
local MAST="em-35kv-catenary-pole"
local function state()
  storage.em=storage.em or {}
  storage.em.native_wire_028=storage.em.native_wire_028
    or {anchors={},edges={},last_sync={}}
  local s=storage.em.native_wire_028
  s.anchors=s.anchors or {};s.edges=s.edges or {};s.last_sync=s.last_sync or {}
  return s
end
function M.ensure_storage() return state() end
local function helper(id)
  local e=id and game.get_entity_by_unit_number(id)
  if e and e.valid and e.name==HELPER then return e end
end
local function erase(record)
  local e=record and helper(record.anchor_id)
  if e then e.destroy() end
end
local function wire(entity)
  return entity.get_wire_connector(defines.wire_connector_id.pole_copper,true)
end
-- Cleanup is intentional ONLY during initialization/version migration or
-- via an explicit diagnostic rebuild. Also clears 0.1.26/27 test helpers.
function M.reset()
  local s=state()
  for _,surface in pairs(game.surfaces) do
    for _,e in pairs(surface.find_entities_filtered{name={HELPER,LEGACY}}) do
      if e.valid then e.destroy() end
    end
  end
  s.anchors={};s.edges={};s.last_sync={}
end
local function parent(n)
  local e=n and game.get_entity_by_unit_number(n.id)
  if e and e.valid and e.name==MAST
    and e.surface.index==n.surface_index
    and e.force.name==n.force_name then return e end
end
local function same_position(a,b)
  return a and b and math.abs(a.x-b.x)<0.001
    and math.abs(a.y-b.y)<0.001
end
local function make_anchor(n)
  local e=parent(n)
  local tip=geo.tip({x=n.x,y=n.y},n.face)
  if not (e and tip) then return nil end
  local a=e.surface.create_entity{
    name=HELPER,position=tip,force=e.force,
    create_build_effect_smoke=false,raise_built=false,snap_to_grid=false}
  if not (a and a.valid and a.unit_number) then
    log("[EM 35kV] failed to create anchor at "..n.x..","..n.y)
    return nil
  end
  a.destructible=false
  return {anchor_id=a.unit_number,face=n.face,x=tip.x,y=tip.y}
end
-- Only graph contacts are accepted. The graph is generated by power_019,
-- which independently checks custom HSR proximity, corridor and real rail
-- connectivity, including curves. This service never joins arbitrary poles.
function M.sync(nodes,edges)
  local s=state()
  local desired,required={},{}
  for _,edge in pairs(edges) do
    if edge.kind=="contact" then
      local a,b=nodes[edge.a],nodes[edge.b]
      if geo.eligible(a,b) then
        local key=geo.key(a.id,b.id)
        desired[key]={a=a.id,b=b.id}
        required[a.id]=a;required[b.id]=b
      end
    end
  end
  -- Reposition if facing or physical mast position changes; delete all
  -- native wires owned by a deleted anchor automatically.
  for id,record in pairs(s.anchors) do
    local n=required[id]
    local tip=n and geo.tip({x=n.x,y=n.y},n.face)
    if not n or not parent(n) or not helper(record.anchor_id)
      or record.face~=n.face or not same_position(tip,record) then
      erase(record)
      s.anchors[id]=nil
    end
  end
  for id,n in pairs(required) do
    if not s.anchors[id] then s.anchors[id]=make_anchor(n) end
  end
  -- Isolate the helper subsystem from ordinary Factorio factory poles.
  -- Also remove stale/manual internal links not present in the HSR graph.
  for mast_id,record in pairs(s.anchors) do
    local a=helper(record.anchor_id)
    if a then
      local ca=wire(a)
      if ca then
        for _,connection in pairs(ca.connections) do
          local cb=connection.target
          local other=cb and cb.owner
          local other_mast_id=nil
          if other and other.valid and other.name==HELPER then
            for id,rec in pairs(s.anchors) do
              if rec.anchor_id==other.unit_number then
                other_mast_id=id;break
              end
            end
          end
          local key=other_mast_id and geo.key(mast_id,other_mast_id)
          if not (key and desired[key]) then
            ca.disconnect_from(cb,connection.origin or defines.wire_origin.player)
          end
        end
      end
    end
  end
  local joined,failed={},0
  for key,link in pairs(desired) do
    local a=s.anchors[link.a] and helper(s.anchors[link.a].anchor_id)
    local b=s.anchors[link.b] and helper(s.anchors[link.b].anchor_id)
    if a and b then
      local ca,cb=wire(a),wire(b)
      if ca and cb and ca.can_wire_reach(cb) then
        if ca.is_connected_to(cb,defines.wire_origin.player)
          or ca.connect_to(cb,true,defines.wire_origin.player) then
          joined[key]={a=link.a,b=link.b}
        else failed=failed+1 end
      else failed=failed+1 end
    else failed=failed+1 end
  end
  s.edges=joined
  local n=0;for _ in pairs(required) do n=n+1 end
  local e=0;for _ in pairs(desired) do e=e+1 end
  s.last_sync={rail_masts=n,desired=e,connected=(e-failed),failed=failed}
  if failed>0 then
    log("[EM 35kV] native span errors: "..failed.." / "..e
      .." (connector reach or helper missing)")
  end
end
function M.status(player,nodes,edges)
  local s=state()
  local stats=s.last_sync
  local anchors=0;for _ in pairs(s.anchors) do anchors=anchors+1 end
  local links=0;for _ in pairs(s.edges) do links=links+1 end
  local total,unqualified=0,0
  for _,edge in pairs(edges or {}) do
    if edge.kind=="contact" then
      total=total+1
      if not geo.eligible(nodes[edge.a],nodes[edge.b]) then
        unqualified=unqualified+1
      end
    end
  end
  local msg=string.format(
    "[EM 35kV] auto wire: anchors=%d contacts=%d native=%d rejected=%d failed=%d; 35kV label only, transfer_MW=0",
    anchors,total,links,unqualified,stats.failed or 0)
  player.print(msg);log(msg)
end
return M
