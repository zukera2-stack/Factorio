#!/usr/bin/env python3
"""Research-only exact-EM070 native bridge buffer -> LuaBurner joule proof.

This runner never publishes or installs a game mod. It unpacks a pre-existing
0.1.62 game ZIP into a *disposable* test directory, verifies EM070 core blobs,
appends a local test-only remote interface, and executes real Factorio with a
native finite accumulator source and real EM070 bridge in manual import mode.
"""
import argparse
import hashlib
import json
import re
import shutil
import socket
import subprocess
import time
import zipfile
from pathlib import Path

CORE_SHA = {
    "scripts/power_bridge_058.lua": "4a4084e5cf71d57cc057aa15bc524ac68ff6268b",
    "scripts/technical_network_046.lua": "e8b1bad35fb60d22bdb91d2dd1c4c5055c58e172",
    "scripts/bridge_dispatch_059.lua": "4f4399d6277c27ec65b73d45fd1bf82f89d4bfe2",
    "scripts/control.lua": "3546d3b7c983856c367279d5dac21fe1c8b07f95",
}

def git_blob(data: bytes) -> str:
    return hashlib.sha1(b"blob "+str(len(data)).encode()+b"\0"+data).hexdigest()

def invoke(cmd, path, timeout=65):
    with path.open("w", encoding="utf8") as o:
        subprocess.run(cmd, stdout=o, stderr=subprocess.STDOUT, timeout=timeout, check=True)
    return path.read_text(encoding="utf8")

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--factorio",type=Path,required=True)
    parser.add_argument("--game-zip",type=Path,required=True,help="Existing CI game ZIP, not generated by this runner")
    parser.add_argument("--output",type=Path,required=True)
    args=parser.parse_args()
    exe=args.factorio.resolve();out=args.output.resolve();src=Path(__file__).resolve().parent/"em072a2-grid-debit-probe"
    if not exe.is_file(): raise FileNotFoundError(exe)
    if not args.game_zip.is_file(): raise FileNotFoundError(args.game_zip)
    if not (src/"test-hook.lua").is_file(): raise FileNotFoundError(src/"test-hook.lua")
    out.mkdir(parents=True,exist_ok=True)
    mods=out/"mods";mods.mkdir(exist_ok=True)
    game_mod=mods/"ElectrifiedMainline"
    if game_mod.exists(): shutil.rmtree(game_mod)
    game_mod.mkdir()
    with zipfile.ZipFile(args.game_zip) as z:
        for n in z.namelist():
            p=Path(n)
            if p.parts[0] not in ("ElectrifiedMainline", "ElectrifiedMainline_0.1.62") or ".." in p.parts: raise ValueError("Unsupported or unsafe game ZIP path "+n)
            if len(p.parts)==1 or n.endswith("/"): continue
            d=game_mod.joinpath(*p.parts[1:]);d.parent.mkdir(parents=True,exist_ok=True)
            d.write_bytes(z.read(n))
    meta=json.loads((game_mod/"info.json").read_text(encoding="utf8"))
    assert meta["name"]=="ElectrifiedMainline" and meta["version"]=="0.1.62"
    for path,sha in CORE_SHA.items():
        content=(game_mod/path).read_bytes()
        assert git_blob(content)==sha, f"Tested EM070 source mismatch: {path}"
    # The only modification to the real game source, restricted to scratch runtime.
    with (game_mod/"control.lua").open("a",encoding="utf8") as f:f.write("\n"+(src/"test-hook.lua").read_text(encoding="utf8"))
    probe=mods/"em072-a2-probe_0.0.1"
    if probe.exists(): shutil.rmtree(probe)
    probe.mkdir()
    for f in ("info.json","data.lua","control.lua"):shutil.copy2(src/f,probe/f)
    names=[("base",True),("space-age",False),("elevated-rails",False),("quality",False),("recycler",False),("ElectrifiedMainline",True),("em072-a2-probe",True)]
    (mods/"mod-list.json").write_text(json.dumps({"mods":[{"name":n,"enabled":v} for n,v in names]}),encoding="utf8")
    private=out/"private";(private/"saves").mkdir(parents=True,exist_ok=True)
    (out/"config.ini").write_text(f'[path]\nread-data={exe.parents[2]/"data"}\nwrite-data={private}\n',encoding="utf8")
    cmd=[str(exe),"--config",str(out/"config.ini"),"--mod-directory",str(mods)]
    invoke(cmd+["--create",str(out/"start.zip")],out/"create.log")
    native=invoke(cmd+["--benchmark",str(out/"start.zip"),"--benchmark-ticks","380","--benchmark-runs","1"],out/"native.log")
    evidence={
      "native": "[EM072A2 NATIVE PASS]",
      "unconnected": "[EM072A2 NO UNCONNECTED FEED PASS]",
      "off": "[EM072A2 OFF PASS]",
    }
    for key,mark in evidence.items():assert mark in native,f"Missing {key} native proof"
    match=re.search(r"\[EM072A2 NATIVE PASS\].*?J=(\d+) consumed_J=(\d+) energy_residual=([-\d.]+)",native)
    assert match and int(match[1])>5000000 and int(match[2])>5000000 and abs(float(match[3]))<0.01
    # Real server SAVE mid-traction with non-zero native bridge buffers and burner.
    marker="-- EM072A2_DISK_SAVE_HOOK"
    original=(probe/"control.lua").read_text(encoding="utf8")
    assert original.count(marker)==1
    hook="""if t==151 then
      local ok,err=pcall(function() game.server_save('em072a2-checkpoint') end)
      log('[EM072A2 DISK SAVE] t=151 requested='..tostring(ok)..' err='..tostring(err))
    end"""
    (probe/"control.lua").write_text(original.replace(marker,hook),encoding="utf8")
    invoke(cmd+["--create",str(out/"server-start.zip")],out/"server-create.log")
    server={"name":"EM072-A2 isolated finite EM070 native fixture","description":"Disposable only",
            "max_players":1,"visibility":{"public":False,"lan":False},
            "require_user_verification":False,"auto_pause":False,"autosave_interval":100}
    (out/"server-settings.json").write_text(json.dumps(server),encoding="utf8")
    with socket.socket() as sock:sock.bind(("127.0.0.1",0));port=sock.getsockname()[1]
    logfile=out/"save-server.log"
    with logfile.open("w",encoding="utf8") as o:
        proc=subprocess.Popen(cmd+["--start-server",str(out/"server-start.zip"),"--server-settings",str(out/"server-settings.json"),"--port",str(port)],stdout=o,stderr=subprocess.STDOUT)
        try:
            checkpoint=private/"saves/em072a2-checkpoint.zip"
            for _ in range(180):
                time.sleep(.25)
                log=logfile.read_text(encoding="utf8",errors="replace")
                if proc.poll() is not None:raise RuntimeError("Server exited: "+log[-1800:])
                if checkpoint.is_file() and "[EM072A2 DISK SAVE] t=151 requested=true" in log and "Saving finished" in log:break
                if "Error while running event" in log:raise RuntimeError(log[-1800:])
            else:raise TimeoutError("Native server did not save at tick 151")
        finally:
            proc.terminate()
            try:proc.wait(timeout=5)
            except subprocess.TimeoutExpired:proc.kill();proc.wait()
    resumed=invoke(cmd+["--test-save",str(checkpoint),"--test-ticks","210"],out/"native-reload.log")
    for mark in evidence.values():assert mark in resumed,"After true SAVE/LOAD missing "+mark
    report={"status":"PASS","engine":"Factorio 2.1.24 build 87808","core_sha":CORE_SHA,
            "test":"native 25kV EM070 bridge manual import -> native EEI output storage -> native LuaBurner",
            "source_initial_j":25000000,"energy_sent_to_burner_j_at_tick_240":int(match[1]),
            "native_burner_consumed_j_at_tick_240":int(match[2]),
            "residual_j":float(match[3]),"native_ticks":380,"save_tick":151,"resume_ticks":210,
            "disconnected_vanilla_rail_credited_j":0,"bridge_OFF_burner_recharge_j":0,
            "no_LuaTrain_speed_writes":True,"test_hook_only_in_disposable_extraction":True,
            "saved_map_bytes":checkpoint.stat().st_size,
            "native_log_sha256":hashlib.sha256((out/"native.log").read_bytes()).hexdigest(),
            "reload_log_sha256":hashlib.sha256((out/"native-reload.log").read_bytes()).hexdigest(),
            "limitations":["Native bridge manually forced to import; auto-dispatch does not yet see train demand",
                "Test hook maps a fixed station to HSR locomotive, does not prove arbitrary rail component association",
                "No real ElectrifiedMainline production traction code modified", "No motor wagons, batteries or regenerative braking",
                "No autonomous train schedule, multiplayer, cut physical powered HSR rail, UPS benchmark"]}
    (out/"report.json").write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf8")
    print("[EM072A2 EM070 NATIVE DISK PASS] "+json.dumps(report,ensure_ascii=False))

if __name__=="__main__":main()
